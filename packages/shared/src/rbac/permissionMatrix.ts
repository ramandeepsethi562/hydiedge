export function hasModulePermission(
  role: SystemRole,
  moduleKey: ModuleKey,
  verb: PermissionVerb,
  customOverrides?: Partial<Record<ModuleKey, PermissionVerb[]>>
): boolean {
  if (role === 'SUPER_ADMIN' || role === 'ORG_ADMIN') return true;
  const source = customOverrides?.[moduleKey] ?? DEFAULT_ROLE_PERMISSION_MATRIX[role]?.[moduleKey] ?? [];
  return source.includes(verb);
}

export function hasSensitiveGateAccess(
  role: SystemRole,
  gate: SensitivePermissionGate,
  explicitlyGrantedGates?: SensitivePermissionGate[]
): boolean {
  if (explicitlyGrantedGates?.includes(gate)) return true;
  return SENSITIVE_GATE_DEFAULTS[gate].includes(role);
}
